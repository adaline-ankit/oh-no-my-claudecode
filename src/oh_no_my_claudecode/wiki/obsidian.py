"""Obsidian vault export for ONMC memory."""

from __future__ import annotations

import json
import re
from collections import defaultdict
from hashlib import sha256
from pathlib import Path

from oh_no_my_claudecode.models import MemoryEntry
from oh_no_my_claudecode.models.memory_edge import EdgeType, MemoryEdge
from oh_no_my_claudecode.storage import SQLiteStorage

_EDGE_LABELS: dict[EdgeType, str] = {
    EdgeType.SUPERSEDES: "supersedes",
    EdgeType.CONTRADICTS: "contradicts",
    EdgeType.RELATES: "relates to",
    EdgeType.DUPLICATE_OF: "duplicates",
}


def build_obsidian_vault(storage: SQLiteStorage, repo_root: Path) -> dict[str, str]:
    """Build deterministic Obsidian notes with graph-producing wikilinks."""
    memories = sorted(storage.list_memories(), key=lambda item: (item.title.casefold(), item.id))
    edges = storage.list_memory_edges()
    note_names = {memory.id: _note_name(memory) for memory in memories}
    memories_by_id = {memory.id: memory for memory in memories}
    relationships = _relationships(edges)
    areas = _group_by_area(memories)

    pages: dict[str, str] = {
        "Home.md": _home_page(repo_root, memories, areas, note_names),
        "Graph.md": _graph_page(edges, memories_by_id, note_names),
    }
    for memory in memories:
        pages[f"Memories/{note_names[memory.id]}.md"] = _memory_page(
            memory,
            relationships.get(memory.id, []),
            memories_by_id,
            note_names,
        )
    for area, area_memories in sorted(areas.items()):
        pages[f"Subsystems/{_slug(area)}.md"] = _subsystem_page(
            area,
            area_memories,
            note_names,
        )
    return pages


def _note_name(memory: MemoryEntry) -> str:
    title_slug = _slug(memory.title)[:72].rstrip("-")
    id_digest = sha256(memory.id.encode("utf-8")).hexdigest()[:8]
    return f"{title_slug}-{id_digest}"


def _slug(value: str) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", value.casefold()).strip("-")
    return slug or "memory"


def _area(memory: MemoryEntry) -> str:
    parts = Path(memory.source_ref.strip().lstrip("/")).parts
    return parts[0] if len(parts) >= 2 else memory.source_type.value


def _group_by_area(memories: list[MemoryEntry]) -> dict[str, list[MemoryEntry]]:
    grouped: dict[str, list[MemoryEntry]] = defaultdict(list)
    for memory in memories:
        grouped[_area(memory)].append(memory)
    return dict(grouped)


def _relationships(
    edges: list[MemoryEdge],
) -> dict[str, list[tuple[str, str, float]]]:
    related: dict[str, list[tuple[str, str, float]]] = defaultdict(list)
    for edge in edges:
        label = _EDGE_LABELS[edge.edge_type]
        related[edge.from_memory_id].append((label, edge.to_memory_id, edge.confidence))
        related[edge.to_memory_id].append(
            (f"{label} (incoming)", edge.from_memory_id, edge.confidence)
        )
    return dict(related)


def _yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _memory_page(
    memory: MemoryEntry,
    relationships: list[tuple[str, str, float]],
    memories_by_id: dict[str, MemoryEntry],
    note_names: dict[str, str],
) -> str:
    tags = ["onmc-memory", f"onmc/{memory.kind.value}"]
    tags.extend(_slug(tag) for tag in memory.tags if _slug(tag))
    lines = [
        "---",
        f"id: {_yaml_string(memory.id)}",
        f"kind: {_yaml_string(memory.kind.value)}",
        f"source_type: {_yaml_string(memory.source_type.value)}",
        f"source_ref: {_yaml_string(memory.source_ref)}",
        f"confidence: {memory.confidence:.2f}",
        "tags:",
        *[f"  - {_yaml_string(tag)}" for tag in dict.fromkeys(tags)],
        "---",
        "",
        f"# {memory.title}",
        "",
        memory.summary.strip(),
        "",
        "## Provenance",
        "",
        f"- Source: `{memory.source_ref or memory.source_type.value}`",
        f"- Kind: `{memory.kind.value}`",
        f"- Confidence: `{memory.confidence:.0%}`",
        f"- Subsystem: [[Subsystems/{_slug(_area(memory))}|{_area(memory)}]]",
        "",
    ]
    details = memory.details.strip()
    if details and details != memory.summary.strip():
        lines.extend(["## Evidence", "", details, ""])
    if relationships:
        lines.extend(["## Relationships", ""])
        for label, other_id, confidence in sorted(relationships):
            other = memories_by_id.get(other_id)
            other_name = note_names.get(other_id)
            if other is None or other_name is None:
                continue
            lines.append(
                f"- {label} [[{other_name}|{other.title}]] (confidence `{confidence:.0%}`)"
            )
        lines.append("")
    lines.extend(["---", "Generated by `onmc wiki --format obsidian`.", ""])
    return "\n".join(lines)


def _home_page(
    repo_root: Path,
    memories: list[MemoryEntry],
    areas: dict[str, list[MemoryEntry]],
    note_names: dict[str, str],
) -> str:
    lines = [
        "---",
        "tags:",
        "  - onmc-vault",
        "---",
        "",
        f"# {repo_root.name} Brain",
        "",
        f"**{len(memories)} memories** connected from repository history, docs, and sessions.",
        "",
        "Open Obsidian Graph View to explore links. Start with [[Graph]].",
        "",
        "## Subsystems",
        "",
    ]
    if areas:
        for area, items in sorted(areas.items()):
            lines.append(f"- [[Subsystems/{_slug(area)}|{area}]] ({len(items)})")
    else:
        lines.append("_No memories yet. Run `onmc ingest` first._")
    lines.extend(["", "## Recent Memory", ""])
    for memory in sorted(memories, key=lambda item: item.updated_at, reverse=True)[:12]:
        lines.append(f"- [[{note_names[memory.id]}|{memory.title}]] `{memory.kind.value}`")
    lines.extend(["", "Generated by `onmc wiki --format obsidian`.", ""])
    return "\n".join(lines)


def _subsystem_page(
    area: str,
    memories: list[MemoryEntry],
    note_names: dict[str, str],
) -> str:
    lines = [
        "---",
        "tags:",
        "  - onmc-subsystem",
        "---",
        "",
        f"# {area}",
        "",
        "[[Home|Back to vault home]]",
        "",
    ]
    by_kind: dict[str, list[MemoryEntry]] = defaultdict(list)
    for memory in memories:
        by_kind[memory.kind.value].append(memory)
    for kind, items in sorted(by_kind.items()):
        lines.extend([f"## {kind.replace('_', ' ').title()}", ""])
        for memory in sorted(items, key=lambda item: item.title.casefold()):
            lines.append(f"- [[{note_names[memory.id]}|{memory.title}]]")
        lines.append("")
    return "\n".join(lines)


def _graph_page(
    edges: list[MemoryEdge],
    memories_by_id: dict[str, MemoryEntry],
    note_names: dict[str, str],
) -> str:
    lines = ["# Memory Graph", "", "[[Home|Back to vault home]]", ""]
    if not edges:
        lines.extend(["_No relationships yet. Run `onmc consolidate` to create edges._", ""])
        return "\n".join(lines)
    for edge in sorted(edges, key=lambda item: (item.edge_type.value, item.from_memory_id)):
        source = memories_by_id.get(edge.from_memory_id)
        target = memories_by_id.get(edge.to_memory_id)
        if source is None or target is None:
            continue
        lines.append(
            f"- [[{note_names[source.id]}|{source.title}]] "
            f"{_EDGE_LABELS[edge.edge_type]} "
            f"[[{note_names[target.id]}|{target.title}]]"
        )
    lines.append("")
    return "\n".join(lines)
