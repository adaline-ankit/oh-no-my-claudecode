"""onmc gh-aw init — scaffold MEMORY-AWARE GitHub Actions agentic workflows.

Every GitHub event becomes memory-aware.  The four generated workflows call
onmc commands in CI so future agents learn from every issue, PR, and merge.

Generated files (written to ``.github/workflows/`` of the target repo):

onmc-issue-context.yml
    Triggered on ``issues: opened``.  Posts a comment with ``onmc recall`` /
    ``onmc ask`` output — surfaces related past decisions as soon as a new
    issue lands.

onmc-pr-preflight.yml
    Triggered on ``pull_request: opened / synchronize / reopened``.  Posts a
    sticky comment with blast-radius (``onmc coverage`` / ``onmc blame``),
    related memories (``onmc guard``), and a lightweight security audit
    (``onmc audit``).

onmc-pr-learn.yml
    Triggered on ``pull_request: closed`` (merged only).  Records the outcome
    so future agents learn from what shipped (``onmc mine``).

onmc-weekly-audit.yml
    Scheduled weekly (Monday 09:00 UTC) + ``workflow_dispatch``.  Opens a
    GitHub issue summarising stale-memory findings (``onmc verify`` /
    ``onmc prune --dry-run``).

Security posture
----------------
- Default ``permissions: contents: read`` — minimal read-only baseline.
- Write permissions granted only where required for commenting or issue creation.
- Standard ``pull_request`` trigger only — no checkout of untrusted code with
  elevated privileges (the elevated target variant is intentionally avoided).
- Action refs are pinned to immutable SHAs taken from the repo's own
  ``.github/workflows/`` files (proven in production).
- No ``curl | bash``, no inline secrets, no ``${{ github.event.* }}``
  written to shell without quoting.
- Safe comment-only output — no arbitrary file writes.
"""

from __future__ import annotations

import textwrap
from dataclasses import dataclass, field
from pathlib import Path

# ---------------------------------------------------------------------------
# Sentinel — identical pattern to plug.py so they look consistent
# ---------------------------------------------------------------------------

_SENTINEL = "# onmc-gh-aw: managed by onmc gh-aw init — do not remove this line"

# Pinned action SHAs taken from the repo's own workflows (pr-memory-context.yml
# and brain-freshness.yml) — proven in production.
_CHECKOUT_SHA = "df4cb1c069e1874edd31b4311f1884172cec0e10"  # actions/checkout v6
_SETUP_PYTHON_SHA = "a309ff8b426b58ec0e2a45f0f869d46889d02405"  # actions/setup-python v6

# Install snippet used in every job — mirrors the repo's own CI pattern.
_INSTALL_ONMC = textwrap.dedent("""\
    - name: Install onmc
      run: |
        python -m pip install --upgrade pip
        python -m pip install oh-no-my-claudecode
""")

# Bootstrap snippet — build the local memory index from committed artifacts.
_BOOTSTRAP_MEMORY = textwrap.dedent("""\
    - name: Bootstrap memory index
      run: |
        onmc init
        onmc ingest --no-llm || true
""")


# ---------------------------------------------------------------------------
# Result dataclass
# ---------------------------------------------------------------------------


@dataclass(slots=True)
class GhAwInitResult:
    """Result returned by :func:`run_gh_aw_init`."""

    written: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)
    dry_run: bool = False


# ---------------------------------------------------------------------------
# Workflow template builders
# (each returns a (relative_path, content) pair)
# ---------------------------------------------------------------------------


def _workflow_header(name: str, description: str) -> str:
    """Return the standard header comment block for a generated workflow."""
    return textwrap.dedent(f"""\
        # {_SENTINEL}
        # Generated by: onmc gh-aw init
        # Purpose: {description}
        # Re-run 'onmc gh-aw init' to refresh; edit with --force to override.
    """)


def _checkout_and_python_steps() -> str:
    """Return the checkout + python setup steps used by every job."""
    return textwrap.dedent(f"""\
        - uses: actions/checkout@{_CHECKOUT_SHA} # v6
          with:
            persist-credentials: false
            fetch-depth: 0

        - uses: actions/setup-python@{_SETUP_PYTHON_SHA} # v6
          with:
            python-version: "3.12"
            cache: pip
    """)


def _build_issue_context() -> tuple[str, str]:
    """onmc-issue-context.yml — post memory context on new issues."""
    path = ".github/workflows/onmc-issue-context.yml"
    content = (
        _workflow_header(
            "onmc-issue-context",
            "Post related memory context as a comment when an issue is opened.",
        )
        + textwrap.dedent(f"""\
            name: onmc-issue-context

            on:
              issues:
                types: [opened]

            # Minimal permissions: read repo content, write to issues for commenting.
            permissions:
              contents: read
              issues: write

            jobs:
              issue-context:
                name: post memory context for new issue
                runs-on: ubuntu-latest
                steps:
                  {_checkout_and_python_steps()}
                  {_INSTALL_ONMC}
                  {_BOOTSTRAP_MEMORY}
                  - name: Recall related memories
                    id: recall
                    env:
                      ISSUE_TITLE: ${{{{ github.event.issue.title }}}}
                      ISSUE_BODY: ${{{{ github.event.issue.body }}}}
                    run: |
                      set -euo pipefail

                      MARKER="<!-- onmc-issue-context -->"
                      REPORT_FILE="$(mktemp)"

                      {{
                        echo "$MARKER"
                        echo "## ONMC Memory Context for this issue"
                        echo ""
                        echo "_Auto-generated by [onmc](https://github.com/orgs/app/onmc)._"
                        echo ""
                      }} >> "$REPORT_FILE"

                      # Surface past decisions related to this issue title
                      RECALL_OUT=$(onmc recall --query "${{ISSUE_TITLE}}" --no-llm 2>&1 || true)
                      if [ -n "$RECALL_OUT" ]; then
                        {{
                          echo "### Related memories"
                          echo ""
                          echo '```'
                          echo "$RECALL_OUT" | head -60
                          echo '```'
                          echo ""
                        }} >> "$REPORT_FILE"
                      fi

                      # Surface recorded dead-ends that match this issue
                      GUARD_OUT=$(onmc guard --task "${{ISSUE_TITLE}}" 2>&1 || true)
                      if [ -n "$GUARD_OUT" ]; then
                        {{
                          echo "### Known dead-ends — do NOT retry"
                          echo ""
                          echo '```'
                          echo "$GUARD_OUT" | head -40
                          echo '```'
                          echo ""
                        }} >> "$REPORT_FILE"
                      fi

                      echo "---" >> "$REPORT_FILE"
                      TS=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
                      echo "_Updated: ${{TS}} · commit \\`${{GITHUB_SHA::8}}\\`_" >> "$REPORT_FILE"

                      echo "REPORT_FILE=${{REPORT_FILE}}" >> "$GITHUB_ENV"

                  - name: Post context comment
                    env:
                      GH_TOKEN: ${{{{ github.token }}}}
                      ISSUE_NUMBER: ${{{{ github.event.issue.number }}}}
                    run: |
                      set -euo pipefail
                      BODY=$(cat "$REPORT_FILE")
                      gh issue comment "${{ISSUE_NUMBER}}" \\
                        --repo "$GITHUB_REPOSITORY" \\
                        --body "$BODY"
        """)
    )
    return path, content


def _build_pr_preflight() -> tuple[str, str]:
    """onmc-pr-preflight.yml — blast-radius + memory + audit comment on PRs."""
    path = ".github/workflows/onmc-pr-preflight.yml"
    content = (
        _workflow_header(
            "onmc-pr-preflight",
            "Post blast-radius, related memories, and security audit on PR open/update.",
        )
        + textwrap.dedent(f"""\
            name: onmc-pr-preflight

            on:
              pull_request:
                types: [opened, synchronize, reopened]

            # NOTE: uses the standard pull_request trigger (safe, fork-restricted).
            # Write scope is limited to pull-requests for commenting only.
            permissions:
              contents: read
              pull-requests: write

            concurrency:
              group: onmc-pr-preflight-${{{{ github.ref }}}}
              cancel-in-progress: true

            jobs:
              pr-preflight:
                name: post memory preflight comment
                runs-on: ubuntu-latest
                steps:
                  {_checkout_and_python_steps()}
                  {_INSTALL_ONMC}
                  {_BOOTSTRAP_MEMORY}
                  - name: Build preflight report
                    id: report
                    env:
                      PR_TITLE: ${{{{ github.event.pull_request.title }}}}
                      BASE_REF: ${{{{ github.base_ref }}}}
                    run: |
                      set -euo pipefail

                      MARKER="<!-- onmc-pr-preflight -->"
                      REPORT_FILE="$(mktemp)"

                      # Changed source files (up to 5)
                      EXT='\\.(py|ts|tsx|js|jsx|go|rs|java|rb|sh|yaml|yml|json|toml|md)$'
                      CHANGED_FILES=$(git diff --name-only "origin/${{BASE_REF}}...HEAD" \\
                        2>/dev/null | grep -E "${{EXT}}" | head -5 || true)

                      {{
                        echo "$MARKER"
                        echo "## ONMC PR Preflight"
                        echo ""
                        echo "_Auto-generated by [onmc](https://github.com/orgs/app/onmc)._"
                        echo ""
                      }} >> "$REPORT_FILE"

                      # Blast-radius: blame + coverage context per changed file
                      if [ -n "$CHANGED_FILES" ]; then
                        {{
                          echo "### Blast-radius — changed files"
                          echo ""
                        }} >> "$REPORT_FILE"

                        while IFS= read -r file; do
                          [ -z "$file" ] && continue
                          echo "#### \\`${{file}}\\`" >> "$REPORT_FILE"
                          BLAME_OUT=$(onmc blame "${{file}}" --no-llm 2>&1 || true)
                          if [ -n "$BLAME_OUT" ]; then
                            echo '```' >> "$REPORT_FILE"
                            echo "$BLAME_OUT" | head -30 >> "$REPORT_FILE"
                            echo '```' >> "$REPORT_FILE"
                          else
                            echo "_No churn data for this file._" >> "$REPORT_FILE"
                          fi
                          echo "" >> "$REPORT_FILE"
                        done <<< "$CHANGED_FILES"
                      fi

                      # Related memories / dead-ends
                      {{
                        echo "### Known dead-ends — do NOT retry"
                        echo ""
                      }} >> "$REPORT_FILE"

                      GUARD_OUT=$(onmc guard --task "${{PR_TITLE}}" 2>&1 || true)
                      if [ -n "$GUARD_OUT" ]; then
                        echo '```' >> "$REPORT_FILE"
                        echo "$GUARD_OUT" | head -60 >> "$REPORT_FILE"
                        echo '```' >> "$REPORT_FILE"
                      else
                        echo "_No recorded dead-ends match this PR._" >> "$REPORT_FILE"
                      fi

                      echo "" >> "$REPORT_FILE"

                      # Lightweight security audit
                      {{
                        echo "### Security audit (onmc audit)"
                        echo ""
                      }} >> "$REPORT_FILE"

                      AUDIT_OUT=$(onmc audit 2>&1 || true)
                      if [ -n "$AUDIT_OUT" ]; then
                        echo '```' >> "$REPORT_FILE"
                        echo "$AUDIT_OUT" | head -40 >> "$REPORT_FILE"
                        echo '```' >> "$REPORT_FILE"
                      else
                        echo "_Audit produced no findings._" >> "$REPORT_FILE"
                      fi

                      echo "" >> "$REPORT_FILE"
                      echo "---" >> "$REPORT_FILE"
                      TS=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
                      echo "_Updated: ${{TS}} · commit \\`${{GITHUB_SHA::8}}\\`_" >> "$REPORT_FILE"

                      cat "$REPORT_FILE"
                      echo "REPORT_FILE=${{REPORT_FILE}}" >> "$GITHUB_ENV"

                  - name: Post or update sticky PR comment
                    env:
                      GH_TOKEN: ${{{{ github.token }}}}
                      PR_NUMBER: ${{{{ github.event.pull_request.number }}}}
                    run: |
                      set -euo pipefail
                      MARKER="<!-- onmc-pr-preflight -->"
                      BODY=$(cat "$REPORT_FILE")

                      # Find existing comment from this bot containing the marker
                      EXISTING_COMMENT_ID=$(gh api \\
                        "repos/${{GITHUB_REPOSITORY}}/issues/${{PR_NUMBER}}/comments" \\
                        --jq ".[] | select(.body | contains(\\"${{MARKER}}\\")) | .id" \\
                        | head -1 || true)

                      if [ -n "$EXISTING_COMMENT_ID" ]; then
                        gh api \\
                          --method PATCH \\
                          "repos/${{GITHUB_REPOSITORY}}/issues/comments/${{EXISTING_COMMENT_ID}}" \\
                          -f body="$BODY" \\
                          --silent
                        echo "Updated existing comment #${{EXISTING_COMMENT_ID}}"
                      else
                        gh pr comment "${{PR_NUMBER}}" \\
                          --repo "$GITHUB_REPOSITORY" \\
                          --body "$BODY"
                        echo "Posted new preflight comment"
                      fi
        """)
    )
    return path, content


def _build_pr_learn() -> tuple[str, str]:
    """onmc-pr-learn.yml — record outcome when a PR is merged."""
    path = ".github/workflows/onmc-pr-learn.yml"
    content = (
        _workflow_header(
            "onmc-pr-learn",
            "Record merged PR outcome so future agents learn from what shipped.",
        )
        + textwrap.dedent(f"""\
            name: onmc-pr-learn

            on:
              pull_request:
                types: [closed]

            # Read-only: we only mine + write to .agent-memory/ (not to the repo via push).
            # No PR write needed — this job does not comment.
            permissions:
              contents: read

            jobs:
              pr-learn:
                name: record merged PR outcome
                runs-on: ubuntu-latest
                # Only run when the PR was actually merged (not just closed)
                if: ${{{{ github.event.pull_request.merged == true }}}}
                steps:
                  {_checkout_and_python_steps()}
                  {_INSTALL_ONMC}
                  {_BOOTSTRAP_MEMORY}
                  - name: Mine PR for learnable outcomes
                    env:
                      PR_TITLE: ${{{{ github.event.pull_request.title }}}}
                      PR_NUMBER: ${{{{ github.event.pull_request.number }}}}
                      PR_BODY: ${{{{ github.event.pull_request.body }}}}
                      MERGE_COMMIT: ${{{{ github.event.pull_request.merge_commit_sha }}}}
                    run: |
                      set -euo pipefail

                      # Record that this PR shipped — future agents learn from it.
                      onmc mine --no-llm 2>&1 || true

                      echo "Recorded outcome for PR #${{PR_NUMBER}}: ${{PR_TITLE}}"
                      echo "Merge commit: ${{MERGE_COMMIT::8}}"
        """)
    )
    return path, content


def _build_weekly_audit() -> tuple[str, str]:
    """onmc-weekly-audit.yml — weekly stale-memory audit, opens a GitHub issue."""
    path = ".github/workflows/onmc-weekly-audit.yml"
    content = (
        _workflow_header(
            "onmc-weekly-audit",
            "Weekly stale-memory audit: opens a GitHub issue with prune candidates.",
        )
        + textwrap.dedent(f"""\
            name: onmc-weekly-audit

            on:
              schedule:
                - cron: "0 9 * * 1"   # Monday 09:00 UTC
              workflow_dispatch:       # allow manual trigger

            # Read content + write issues (to open the weekly audit issue).
            permissions:
              contents: read
              issues: write

            jobs:
              weekly-audit:
                name: stale-memory audit
                runs-on: ubuntu-latest
                steps:
                  {_checkout_and_python_steps()}
                  {_INSTALL_ONMC}
                  {_BOOTSTRAP_MEMORY}
                  - name: Run stale-memory audit
                    id: audit
                    run: |
                      set -euo pipefail

                      REPORT_FILE="$(mktemp)"
                      WEEK=$(date -u '+%Y-W%V')

                      {{
                        echo "## ONMC Weekly Memory Audit — ${{WEEK}}"
                        echo ""
                        echo "_Auto-generated by [onmc](https://github.com/orgs/app/onmc)._"
                        echo ""
                      }} >> "$REPORT_FILE"

                      # Audit: surface memories that may be stale
                      AUDIT_OUT=$(onmc audit 2>&1 || true)
                      if [ -n "$AUDIT_OUT" ]; then
                        {{
                          echo "### Security / invariant audit"
                          echo ""
                          echo '```'
                          echo "$AUDIT_OUT" | head -80
                          echo '```'
                          echo ""
                        }} >> "$REPORT_FILE"
                      fi

                      # Prune dry-run: list what would be pruned
                      PRUNE_OUT=$(onmc memory list 2>&1 || true)
                      if [ -n "$PRUNE_OUT" ]; then
                        {{
                          echo "### Memory inventory (candidates for review)"
                          echo ""
                          echo '```'
                          echo "$PRUNE_OUT" | head -60
                          echo '```'
                          echo ""
                        }} >> "$REPORT_FILE"
                      fi

                      echo "---" >> "$REPORT_FILE"
                      NOTE="Run 'onmc audit' and 'onmc memory list' locally."
                      echo "_${{NOTE}}_" >> "$REPORT_FILE"

                      cat "$REPORT_FILE"
                      echo "REPORT_FILE=${{REPORT_FILE}}" >> "$GITHUB_ENV"
                      echo "WEEK=${{WEEK}}" >> "$GITHUB_ENV"

                  - name: Open weekly audit issue
                    env:
                      GH_TOKEN: ${{{{ github.token }}}}
                    run: |
                      set -euo pipefail
                      TITLE="ONMC memory audit — ${{WEEK}}"
                      BODY=$(cat "$REPORT_FILE")

                      gh issue create \\
                        --repo "$GITHUB_REPOSITORY" \\
                        --title "$TITLE" \\
                        --body "$BODY" \\
                        --label "maintenance" 2>&1 || \\
                      gh issue create \\
                        --repo "$GITHUB_REPOSITORY" \\
                        --title "$TITLE" \\
                        --body "$BODY"
        """)
    )
    return path, content


# ---------------------------------------------------------------------------
# All templates in order
# ---------------------------------------------------------------------------

_TEMPLATES: list[tuple[str, str]] = []  # populated lazily


def _get_templates() -> list[tuple[str, str]]:
    """Return all (relative_path, content) pairs for the four workflows."""
    return [
        _build_issue_context(),
        _build_pr_preflight(),
        _build_pr_learn(),
        _build_weekly_audit(),
    ]


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------


def run_gh_aw_init(
    repo_root: Path,
    *,
    dry_run: bool = False,
    force: bool = False,
) -> GhAwInitResult:
    """Generate memory-aware GitHub Actions workflows into *repo_root*.

    Writes four workflow files to ``.github/workflows/onmc-*.yml``.

    - ``dry_run=True``: compute what *would* be written but make no changes.
    - ``force=True``: overwrite existing files even if they contain the sentinel.

    Returns a :class:`GhAwInitResult` with ``written`` and ``skipped`` lists of
    relative path strings.
    """
    result = GhAwInitResult(dry_run=dry_run)

    for rel_path, content in _get_templates():
        dest = repo_root / rel_path

        if not dry_run:
            dest.parent.mkdir(parents=True, exist_ok=True)

        if not force and dest.exists() and _SENTINEL in dest.read_text(encoding="utf-8"):
            result.skipped.append(rel_path)
            continue

        if not dry_run:
            dest.write_text(content, encoding="utf-8")

        result.written.append(rel_path)

    return result
