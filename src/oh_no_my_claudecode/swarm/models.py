"""Data models for the onmc swarm orchestrator.

Honest concurrency note
-----------------------
SwarmConfig.concurrency is the size of the ThreadPoolExecutor worker pool,
NOT the number of truly simultaneous agent processes.  The default is
``min(os.cpu_count() - 1, 8)``.  Actual parallelism is constrained by CPU,
RAM, and API rate limits on the agent backends.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from pathlib import Path

from oh_no_my_claudecode.loop.models import LoopResult


def _default_concurrency() -> int:
    """Return min(cpu_count-1, 8), minimum 1."""
    cpu = os.cpu_count() or 1
    return max(1, min(cpu - 1, 8))


@dataclass
class SwarmUnit:
    """One task unit in the swarm queue.

    Parameters
    ----------
    id:
        Stable identifier for this unit (used in receipts and state files).
    goal:
        Goal text passed to the loop engine as LoopSpec.goal.
    verify_command:
        Shell command run after each iteration.  When ``None``, no verification
        is run (the verify runner always returns passed=False, which means the
        loop runs to max_iterations unless it converges on other grounds).
    """

    id: str
    goal: str
    verify_command: str | None = None


@dataclass
class SwarmConfig:
    """Runtime configuration for a swarm run.

    Concurrency model
    -----------------
    ``concurrency`` controls the ThreadPoolExecutor pool size — the maximum
    number of unit loop runs that execute concurrently.  This is NOT the same
    as the number of agent processes (each loop iteration spawns one agent
    process, so peak load is concurrency * 1 agents at a given moment, but
    typically much less).

    The default ``min(cpu_count-1, 8)`` is conservative and safe on a laptop.
    On a CI machine with 32 cores and no API rate limits you can set it higher,
    but keep the API-rate and RAM constraints in mind.

    Parameters
    ----------
    concurrency:
        Maximum parallel loop runs.  Default min(cpu_count-1, 8), minimum 1.
    agent:
        Which agent CLI to use: "claude" (default), "codex", or "opencode".
    max_iterations:
        Per-unit max loop iterations (default 10).
    budget_tokens:
        Per-unit token budget (default None = no limit).
    max_cost_usd:
        Per-unit cost ceiling in USD (default None = no limit).
    max_wall_seconds:
        Per-unit wall-clock timeout in seconds (default None = no limit).
    swarm_max_cost_usd:
        Swarm-level total cost ceiling in USD.  Once the sum of all completed
        unit costs reaches this value, no new units are launched (already
        running units complete).  Default None = no swarm-level cap.
    isolate:
        When True, each unit runs in its own git worktree (default True).
        Set False to run all units against the same working tree (useful for
        read-only analysis tasks or when git worktree is unavailable).
    """

    concurrency: int = field(default_factory=_default_concurrency)
    agent: str = "claude"
    max_iterations: int = 10
    budget_tokens: int | None = None
    max_cost_usd: float | None = None
    max_wall_seconds: int | None = None
    swarm_max_cost_usd: float | None = None
    isolate: bool = True


@dataclass
class SwarmUnitResult:
    """Result for a single swarm unit.

    Parameters
    ----------
    unit_id:
        Matches SwarmUnit.id.
    status:
        "done" — loop converged or exhausted normally.
        "failed" — loop raised an unhandled exception.
        "aborted" — loop stopped due to external abort signal or swarm cost cap.
    loop_result:
        The LoopResult from run_loop.  None when status is "failed" due to an
        unhandled exception before run_loop returned.
    receipt_path:
        Path to the tamper-evident receipt written after the run.  None for
        aborted/failed units.
    cost_usd:
        Total cost in USD for this unit.  0.0 when not available.
    error:
        Exception message when status is "failed", else None.
    """

    unit_id: str
    status: str  # "done" | "failed" | "aborted"
    loop_result: LoopResult | None
    receipt_path: Path | None
    cost_usd: float
    error: str | None = None


@dataclass
class SwarmResult:
    """Aggregated result for a completed swarm run.

    Parameters
    ----------
    swarm_id:
        Unique identifier for this swarm run (generated by run_swarm).
    unit_results:
        Results for all units, in completion order.
    total_cost_usd:
        Sum of cost_usd across all units.
    total_tokens:
        Sum of total_tokens across all units.
    stop_reason:
        Why the swarm stopped.
        "completed" — all units ran.
        "aborted" — abort was requested externally.
        "cost-cap" — swarm_max_cost_usd reached.
    units_done:
        Count of units with status "done".
    units_failed:
        Count of units with status "failed".
    units_aborted:
        Count of units with status "aborted".
    """

    swarm_id: str
    unit_results: list[SwarmUnitResult] = field(default_factory=list)
    total_cost_usd: float = 0.0
    total_tokens: int = 0
    stop_reason: str = "completed"  # "completed" | "aborted" | "cost-cap"
    units_done: int = 0
    units_failed: int = 0
    units_aborted: int = 0
